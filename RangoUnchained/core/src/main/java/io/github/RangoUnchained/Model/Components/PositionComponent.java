package io.github.RangoUnchained.Model.Components;

public class PositionComponent implements Component {

    private int posX;
    private int posY;

    public PositionComponent() {
    }

    public int getPosX() {
        return posX;
    }

    public void setPosX(int posX) {
        this.posX = posX;
    }

    public int getPosY() {
        return posY;
    }

    public void setPosY(int posY) {
        this.posY = posY;
    }
}


